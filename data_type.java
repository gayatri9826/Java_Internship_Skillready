class data_type{
    public static void main(String[] args) {
        int age=15;//integer datatype
        float salary=20000.500F;//float datatype
        double pi=3.14156789;//double datatype
        char grade='A';//character datatype
        boolean pass=true;//boolean datatype
        String my_name="GAYATRI MALTHANE";//string datatype
        System.out.println("Age:"+age);
        System.out.println("Salary:"+salary);
        System.out.println("Pi:"+pi);
        System.out.println("Grade:"+grade);
        System.out.println("Pass:"+pass);
        System.out.println("Name:"+my_name);
    }
}