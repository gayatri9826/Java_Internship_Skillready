public class IncrementDecrement {
    public static void main(String[] args) {

        int a = 10;

        // Increment Operator
        System.out.println("Initial value of a: " + a);
        a++;
        System.out.println("After Increment: " + a);

        // Decrement Operator
        a--;
        System.out.println("After Decrement: " + a);
    }
}
