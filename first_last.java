//print the first and last element in an array
//a[]{1}
//a[]={1,2,3,4}
public class first_last {
   public static void main(String[] args) {
       int a[]={1,2,3,4,5,6,7};
       System.out.println("first element : "+a[0]);
       System.out.println("last element : "+a[6]);
       System.out.println("length : "+(a.length+1));
       System.out.println("last element :"+(a.length-1));
}
}
