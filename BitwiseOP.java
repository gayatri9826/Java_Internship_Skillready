//Bitwise operator performs operations at binary level
//01 01 01
//bitwise and &
//bitwise or |
//bitwise XOR ^
//bitwise left shift op <<
//right shift op >>
public class BitwiseOP {
    public static void main(String[] args) {
        int a=5;
        int b=3;
        System.out.println("bitwise AND operator =" +(a&b));
        System.out.println("bitwise OR operator =" +(a|b));
        System.out.println("bitwise XOR operator =" +(a^b));
    
    }
}
