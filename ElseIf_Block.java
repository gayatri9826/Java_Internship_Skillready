class ElseIf_Block {

    public static void main(String[] args) {

        int a = 100;

        if (a == 100) {
            System.out.println("a==100");
        }
        else if (a == 200) {
            System.out.println("a==200");
        }
        else if (a == 300) {
            System.out.println("a==300");
        }
        else {
            System.out.println("not possible condition are there");
        }
    }
}